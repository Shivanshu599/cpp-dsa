#include <iostream>
using namespace std;

int main() {

    // Integer data type
    int age = 19;

    // Floating-point data type
    float height = 5.8f;

    // Double data type
    double pi = 3.1415926535;

    // Character data type
    char grade = 'A';

    // Boolean data type
    bool isStudent = true;

    // String data type
    string name = "Shiva";

    cout << "Name: " << name << endl;
    cout << "Age: " << age << endl;
    cout << "Height: " << height << endl;
    cout << "Pi: " << pi << endl;
    cout << "Grade: " << grade << endl;
    cout << "Student: " << isStudent << endl;

    return 0;
}